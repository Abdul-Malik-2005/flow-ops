from collections.abc import AsyncIterator
from contextlib import asynccontextmanager
from typing import Annotated

import httpx
from fastapi import Depends, FastAPI, status
from fastapi.responses import JSONResponse
from sqlalchemy import text
from sqlalchemy.exc import SQLAlchemyError
from sqlalchemy.ext.asyncio import AsyncSession

from app.api.v1.router import router as api_v1_router
from app.core.config import settings
from app.core.security import validate_keys
from app.db.session import engine, get_session


@asynccontextmanager
async def lifespan(app: FastAPI) -> AsyncIterator[None]:
    """Startup/shutdown hooks.

    The JWT public key is loaded eagerly so a misconfigured container crashes at
    start-up instead of returning 500 on the first authenticated request. In
    testing the key pair is generated by the test fixtures, so the check is
    skipped there (same convention as Identity).

    The engine is created at import time, so shutdown only has to dispose of the
    pool.

    One `httpx.AsyncClient` is created for the whole process: creating one per
    request would redo the TCP handshake for every order and make the effective
    latency of the saga step depend on connection churn.
    """
    if settings.environment != "testing":
        validate_keys()
    app.state.inventory_http = httpx.AsyncClient(
        timeout=httpx.Timeout(settings.inventory_timeout_seconds),
    )
    try:
        yield
    finally:
        await app.state.inventory_http.aclose()
        await engine.dispose()


app = FastAPI(
    title="FlowOps Order Service",
    description="Order lifecycle and stock reservation orchestration",
    version="1.0.0",
    lifespan=lifespan,
)

# All public endpoints live under `/api/v1`; the probes stay at the root so a
# platform health check never depends on the API version.
app.include_router(api_v1_router, prefix="/api/v1")


@app.get("/health")
async def health_check():
    """Liveness: the process is up. Never touches the database."""
    return {"status": "healthy"}


@app.get("/ready")
async def readiness_check(
    session: Annotated[AsyncSession, Depends(get_session)],
) -> JSONResponse:
    """Readiness: can this instance actually serve traffic?

    `/health` stays a liveness probe, so an orchestrator does not restart a
    healthy process just because PostgreSQL is briefly away. `/ready` is the
    one to gate traffic on: it reports 503 until `SELECT 1` succeeds.
    """
    try:
        await session.execute(text("SELECT 1"))
    except SQLAlchemyError:
        return JSONResponse(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            content={"status": "unavailable", "database": "error"},
        )
    return JSONResponse(content={"status": "ready", "database": "ok"})

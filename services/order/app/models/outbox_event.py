"""Transactional outbox: messages waiting to be published, written with the fact.

The row is inserted **in the same transaction** as the status change it
describes, so there is no window where an order is `reserved` but the event is
lost (or the other way round). Delivery is a separate process
(`python -m app.outbox_relay`): it claims a batch, publishes, and only then sets
`published_at`.

Two deliberate choices are encoded in the schema:

* `event_type` is a `varchar`, not a native enum: a new event type must not cost
  an `ALTER TYPE` migration (same reasoning as `order_status_history.reason`).
* `payload` is a `jsonb` snapshot, not a reference: a consumer has no right to
  read the Order database, so everything it needs travels inside the message.

Delivery is **at-least-once**, not exactly-once: a crash between `publish()` and
the `published_at` update makes the relay send the same row again. That is why
`id` is generated by the application and travels as `event_id` — it is the key a
consumer must be idempotent by.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import DateTime, Index, Integer, String, func, text
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class OutboxEvent(Base):
    __tablename__ = "outbox_events"

    __table_args__ = (
        # The relay feed: only unpublished rows, so the index stays tiny even
        # though the table is append-only and never cleaned. `(occurred_at, id)`
        # matches the claim order and makes it deterministic when two events
        # share a timestamp.
        Index(
            "ix_outbox_events_unpublished",
            "occurred_at",
            "id",
            postgresql_where=text("published_at IS NULL"),
        ),
    )

    # Generated by the application, not the database: the id is the `event_id`
    # a consumer deduplicates by, and it must be known before `publish()`.
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    # The order this event is about. No FK: the outbox must outlive the
    # aggregate, and a foreign key would only add lock contention.
    aggregate_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        nullable=False,
    )

    event_type: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
    )

    payload: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        nullable=False,
    )

    # When the fact happened, not when it was published: the relay orders by
    # this column so the published stream follows the real order of events.
    occurred_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )

    # NULL means "not delivered yet". The row is marked only *after*
    # `EventPublisherPort.publish()` returns, which is what makes the guarantee
    # at-least-once: a crash in between re-sends the event.
    published_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    # Lease of the current publish attempt. The relay never holds a transaction
    # across the publisher call, so a second relay process must be able to tell
    # "someone is working on this row" from "this row was abandoned".
    locked_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    # Includes failed attempts, because the claim increments it *before* the
    # publish call. Once it reaches the configured maximum the row drops out of
    # the claim predicate and surfaces as an error log instead of being retried
    # forever — events are never deleted, so nothing is lost.
    attempts: Mapped[int] = mapped_column(
        Integer(),
        nullable=False,
        default=0,
        server_default=text("0"),
    )

    def __repr__(self) -> str:
        return (
            f"<OutboxEvent id={self.id} type={self.event_type} "
            f"aggregate={self.aggregate_id} published={self.published_at is not None}>"
        )

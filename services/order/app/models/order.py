"""Order aggregate: the lifecycle of a single customer order.

The ID is generated by the application, not by the database: it is handed to
Inventory as the reservation key *before* the row is committed, so it must be
known up front (see the order-first saga in docs/architecture.md).
"""

from __future__ import annotations

import uuid
from datetime import datetime
from decimal import Decimal
from enum import StrEnum

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    Index,
    Integer,
    Numeric,
    String,
    func,
    text,
)
from sqlalchemy import (
    Enum as SAEnum,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class OrderStatus(StrEnum):
    """States of the order saga.

    `pending` is not a transient cosmetic state: an order stays there while the
    Inventory reservation is unknown (timeout, 5xx). It is reconcilable because
    the reservation call is idempotent by `order_id`.
    """

    PENDING = "pending"
    RESERVED = "reserved"
    PAID = "paid"
    FULFILLED = "fulfilled"
    CANCELLED = "cancelled"
    FAILED = "failed"


def order_status_type() -> SAEnum:
    """Native `order_status` type, shared by `orders` and its history table.

    A factory (not a module-level instance) is used so every column gets its own
    type object: the enum is created once by the migration, while duplicated
    instances keep each column's definition independent.
    """
    return SAEnum(
        OrderStatus,
        name="order_status",
        native_enum=True,
        values_callable=lambda x: [e.value for e in x],
    )


class Order(Base):
    __tablename__ = "orders"

    __table_args__ = (
        CheckConstraint(
            "total_amount IS NULL OR total_amount >= 0",
            name="total_amount_non_negative",
        ),
        CheckConstraint(
            "currency ~ '^[A-Z]{3}$'",
            name="currency_iso_code",
        ),
        # Idempotent creation: a retry with the same key returns the existing
        # order. The index is partial so orders created without a key never
        # conflict with each other on (user_id, NULL).
        Index(
            "uq_orders_user_id_idempotency_key",
            "user_id",
            "idempotency_key",
            unique=True,
            postgresql_where=text("idempotency_key IS NOT NULL"),
        ),
        # Feed for `GET /orders` (newest first, ready for keyset pagination).
        Index(
            "ix_orders_user_id_created_at",
            "user_id",
            text("created_at DESC"),
        ),
        # Reconciler feed: only abandoned `pending` orders, so the index stays
        # tiny even as the table grows.
        Index(
            "ix_orders_pending_created_at",
            "created_at",
            postgresql_where=text("status = 'pending'"),
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    # Users live in Identity DB: no FK can cross a service boundary. The value
    # always comes from a verified token's `sub`, never from the request body.
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        nullable=False,
    )

    status: Mapped[OrderStatus] = mapped_column(
        order_status_type(),
        nullable=False,
        default=OrderStatus.PENDING,
        server_default=text("'pending'"),
    )

    # No server default: the default currency is a business decision that comes
    # from application settings, not something baked into the schema.
    currency: Mapped[str] = mapped_column(
        String(3),
        nullable=False,
    )

    # NULL means "the price is not known yet" (Catalog does not exist). 0.00
    # would be a lie that Payment could act on, so three-valued logic here is
    # the cheaper trade-off.
    total_amount: Mapped[Decimal | None] = mapped_column(
        Numeric(12, 2),
        nullable=True,
    )

    idempotency_key: Mapped[str | None] = mapped_column(
        String(255),
        nullable=True,
    )

    # sha256 of the canonicalised request body: the same key with a different
    # payload is a conflict, not a replay.
    request_hash: Mapped[str | None] = mapped_column(
        String(64),
        nullable=True,
    )

    # Identifier returned by Inventory. Diagnostics only: not a FK, never
    # joined against, the source of truth stays in the Inventory service.
    inventory_reservation_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        nullable=True,
    )

    # Lease on the reserve step: set in TX1 right before the Inventory call and
    # cleared in TX2. While it is fresh, cancellation is refused, because the
    # reservation request may still land and Inventory has no release endpoint —
    # a cancelled order would keep stock blocked forever
    # (docs/architecture.md §5). The reconciler reuses the marker as the start
    # of the *most recent* attempt: an expired marker means "no call in flight",
    # which is exactly the claim predicate.
    reservation_started_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    # How many times the reconciler has claimed the order for a retry. The claim
    # statement increments it *before* the HTTP call, so a worker that dies
    # mid-attempt still spends budget; once the budget is exhausted the order
    # fails as `reservation_unavailable` instead of being retried forever.
    reservation_attempts: Mapped[int] = mapped_column(
        Integer(),
        nullable=False,
        default=0,
        server_default=text("0"),
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    def __repr__(self) -> str:
        return (
            f"<Order id={self.id} user_id={self.user_id} "
            f"status={self.status.value} total={self.total_amount}>"
        )

"""Order positions.

No ORM relationship to `Order` yet: in async SQLAlchemy a lazy relationship is
a `MissingGreenlet` waiting to happen, so children are loaded explicitly with
`selectinload()` in the repository (step 5). The FK stays the single source of
truth for ownership.
"""

from __future__ import annotations

import uuid
from decimal import Decimal

from sqlalchemy import (
    CheckConstraint,
    ForeignKey,
    Integer,
    Numeric,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class OrderItem(Base):
    __tablename__ = "order_items"

    __table_args__ = (
        CheckConstraint("quantity > 0", name="quantity_positive"),
        CheckConstraint(
            "unit_price IS NULL OR unit_price >= 0",
            name="unit_price_non_negative",
        ),
        CheckConstraint(
            "line_total IS NULL OR line_total >= 0",
            name="line_total_non_negative",
        ),
        # Guards against duplicated positions (double-counted quantities) and
        # doubles as the lookup index for `order_id`, since it is the leading
        # column. The name is generated by the naming convention, not set by
        # hand: an explicit `name=` would override `uq_%(table_name)s_...`.
        UniqueConstraint("order_id", "product_id", "warehouse_id"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    # Positions are meaningless without the order, so they die with it. Orders
    # themselves are never hard-deleted (cancellation is a status), so this only
    # matters for manual cleanup and test fixtures.
    order_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("orders.id", ondelete="CASCADE"),
        nullable=False,
    )

    # Catalog and Inventory own their data: cross-service IDs are not FKs here.
    product_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        nullable=False,
    )
    warehouse_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        nullable=False,
    )

    quantity: Mapped[int] = mapped_column(Integer, nullable=False)

    # Snapshot of the price at order time: needs to survive future price-list
    # and rounding changes. NULL until Catalog provides pricing.
    unit_price: Mapped[Decimal | None] = mapped_column(
        Numeric(12, 2),
        nullable=True,
    )
    line_total: Mapped[Decimal | None] = mapped_column(
        Numeric(12, 2),
        nullable=True,
    )

    def __repr__(self) -> str:
        return (
            f"<OrderItem id={self.id} order_id={self.order_id} "
            f"product_id={self.product_id} quantity={self.quantity}>"
        )

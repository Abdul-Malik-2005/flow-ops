"""Verification of access tokens issued by the Identity service.

Order never signs tokens: it only holds Identity's RS256 public key and checks
incoming access tokens locally. A network call to Identity on every request
would turn an authentication problem into an availability problem, and Identity
does not expose a JWKS endpoint (see docs/architecture.md).
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import jwt
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.rsa import RSAPublicKey

from app.core.config import settings


@dataclass(frozen=True, slots=True)
class Principal:
    """Authenticated caller, derived from token claims only.

    Deliberately not an ORM `User`: users live in the Identity database, so
    there is no row to load here. `role` stays a plain string — a new role added
    by Identity must not make every Order request fail.
    """

    user_id: uuid.UUID
    role: str


class InvalidTokenError(Exception):
    """Raised when a token is malformed, expired, or has the wrong type."""


@lru_cache(maxsize=1)
def load_public_key() -> RSAPublicKey:
    """Load and validate Identity's public key once per process."""
    path = Path(settings.jwt_public_key_path).resolve()
    if not path.is_file():
        raise FileNotFoundError(
            f"JWT public key not found at {path}. "
            "Set JWT_PUBLIC_KEY_PATH (see .env.example)."
        )
    key = serialization.load_pem_public_key(path.read_bytes())
    if not isinstance(key, RSAPublicKey):
        raise TypeError(f"Expected an RSA public key, got {type(key).__name__}")
    return key


def validate_keys() -> None:
    """Eagerly load the key so the service fails at startup, not on request 1.

    Called from the application lifespan; skipped in testing, where the key is
    generated by the test fixtures.
    """
    load_public_key()


def decode_access_token(token: str) -> Principal:
    """Verify an access token and return the caller.

    Checks, in order: well-formed header, expected `kid`, signature/expiry via
    PyJWT, `type == "access"`, and a UUID `sub`. Any problem raises
    `InvalidTokenError`; the message is for logs, not for clients.
    """
    try:
        header = jwt.get_unverified_header(token)
    except jwt.InvalidTokenError as exc:
        raise InvalidTokenError("malformed token header") from exc

    # A token signed with another key id cannot be ours, even if the signature
    # happens to verify (e.g. after a key rotation).
    if header.get("kid") != settings.jwt_kid:
        raise InvalidTokenError(
            f"unexpected kid {header.get('kid')!r}, expected {settings.jwt_kid!r}"
        )

    try:
        payload = jwt.decode(
            token,
            load_public_key(),
            algorithms=[settings.jwt_algorithm],
            options={"require": ["exp", "iat", "sub", "type"]},
        )
    except jwt.InvalidTokenError as exc:
        raise InvalidTokenError(str(exc)) from exc

    # A refresh token is a valid JWT signed by Identity, so `type` must be
    # checked explicitly: otherwise it would authenticate requests.
    if payload.get("type") != "access":
        raise InvalidTokenError(f"expected access token, got {payload.get('type')!r}")

    try:
        user_id = uuid.UUID(str(payload["sub"]))
    except (KeyError, ValueError) as exc:
        raise InvalidTokenError("token subject is not a UUID") from exc

    return Principal(user_id=user_id, role=str(payload.get("role", "")))
